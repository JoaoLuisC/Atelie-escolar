// ════════════════════════════════════════════════════════════════════
// Schemas dos recursos CRUD do admin — regra B1, item P2.2.
//
// ── PRINCÍPIO, O MESMO DE validation/index.js ───────────────────────
// Nada nos LIMITES muda. Todo teto aqui replica exatamente o que os cinco
// handlers já aplicavam à mão. A regra B1 é sobre ONDE a validação acontece,
// não sobre endurecer o contrato — mudar as duas coisas de uma vez tornaria
// impossível saber qual delas quebrou a tela da dona da loja.
//
// ── A ÚNICA EXCEÇÃO, E POR QUE ELA VALE ─────────────────────────────
// O `id`. Antes era `String(body.id || '').trim()` e seguia direto para o
// filtro `id=eq.<valor>` do PostgREST. Validar o FORMATO antes de o valor ser
// interpolado ali é a defesa que o comentário de `common.schemas.js:UUID_RE`
// descreve, e é por isso que aquele primitivo existe. Aqui ele ganha uso.
//
// ⚠️ E ele NÃO é uuid em todo lugar: `coupons.id` é
// `bigint generated by default as identity` (supabase/schema.sql:208),
// enquanto categories, products, orders e profiles são `uuid`. Um schema de
// `id` único para os cinco quebraria os cupons em produção sem barulho nenhum
// em dev — conferido no schema, não suposto.
// ════════════════════════════════════════════════════════════════════

const { z } = require('zod');

const { cleanText, uuid } = require('./common.schemas');

// ── Primitivos de identificador ──────────────────────────────────────

/** `id` das tabelas com PK uuid: categories, products, orders, profiles. */
const uuidId = uuid;

/** `id` de `coupons`, que é bigint identity. Aceita número ou string numérica. */
const bigintId = z
  .union([z.number(), z.string()])
  .transform((value) => String(value).trim())
  .refine((value) => /^[1-9]\d{0,18}$/.test(value), { error: 'Identificador inválido.' });

/**
 * Slug derivado do nome, nunca recebido do cliente.
 *
 * Fica aqui e não em `common.schemas.js` porque é forma de SAÍDA da
 * normalização do admin, e não entrada de borda como `uuid` ou `email`.
 */
const slug = z
  .string()
  .trim()
  .toLowerCase()
  .refine((value) => /^[a-z0-9-]+$/.test(value), { error: 'Slug inválido.' });

/**
 * Valor monetário do LADO ADMIN (preço de produto, total de pedido).
 *
 * Diferente de `clientPrice`: aquele é prévia vinda do navegador e nunca é
 * fonte de verdade para cobrança; este É gravado no banco. O teto de 1.000.000
 * é o mesmo — um valor acima disso é digitação errada, não catálogo.
 */
const money = z.coerce
  .number({ error: 'Valor inválido.' })
  .min(0, { error: 'Valor não pode ser negativo.' })
  .max(1_000_000, { error: 'Valor acima do limite.' });

function normalizeSlug(value) {
  return (
    String(value || '')
      .trim()
      .toLowerCase()
      .normalize('NFD')
      .replaceAll(/[\u0300-\u036f]/g, '')
      .replaceAll(/[^a-z0-9]+/g, '-')
      .replaceAll(/^-+|-+$/g, '') || 'sem-categoria'
  );
}

// ── Categorias ───────────────────────────────────────────────────────

const UUID_LOOKING_NAME = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

const categoryName = z
  .unknown()
  .transform(cleanText)
  .refine((value) => value.length > 0, { error: 'Nome da categoria é obrigatório.' })
  // Mantido do handler: colar um ID no campo nome era erro real de operação, e
  // o resultado era uma categoria chamada "8f3c…" no menu da loja.
  .refine((value) => !UUID_LOOKING_NAME.test(value), {
    error: 'Nome inválido: não cole IDs no campo nome.',
  })
  .refine((value) => value.length >= 2 && value.length <= 60, {
    error: 'Nome deve ter entre 2 e 60 caracteres.',
  });

const categoryCreateSchema = z.object({
  name: categoryName,
  color: z.string().trim().optional(),
  active: z.boolean().optional(),
  featured: z.boolean().optional(),
});

const categoryUpdateSchema = z.object({
  id: uuidId,
  name: categoryName.optional(),
  color: z.string().trim().optional(),
  active: z.boolean().optional(),
  featured: z.boolean().optional(),
});

// ── Cupons ───────────────────────────────────────────────────────────

const couponCode = z
  .unknown()
  .transform((value) =>
    String(value ?? '')
      .trim()
      .toUpperCase()
      .replaceAll(/\s+/g, '')
      .slice(0, 64),
  )
  .refine((value) => value.length > 0, { error: 'Código do cupom é obrigatório.' })
  .refine((value) => value.length >= 3, { error: 'Código deve ter ao menos 3 caracteres.' })
  .refine((value) => /^[A-Z0-9._-]+$/.test(value), {
    error: 'Código só pode ter letras, números, ponto, hífen e underscore.',
  });

const discountType = z.enum(['percent', 'fixed'], {
  error: 'Tipo de desconto deve ser percentual ou valor fixo.',
});

/**
 * Data opcional: vazio vira `null`; texto que não é data vira erro.
 *
 * Data SEM hora ("2026-12-31", o que um `<input type="date">` produz) vale até o
 * fim daquele dia no horário de Brasília. `new Date("2026-12-31")` é meia-noite
 * UTC — 30/12 às 21h aqui —, e era isso que fazia a validade do cupom aparecer
 * um dia antes e recuar a cada edição (ADM-39). O painel já manda o instante
 * completo; isto protege quem mandar só a data.
 */
const DATE_ONLY = /^\d{4}-\d{2}-\d{2}$/;
// O INÍCIO vale desde 00:00 do dia (antes ele também virava 23:59, e o cupom
// não valia no próprio dia de início); o FIM vale até 23:59:59.
function brtDate(timeOfDay) {
  return z
    .union([z.string(), z.number(), z.date(), z.null()])
    .transform((value) => {
      if (value === null || String(value).trim() === '') return null;
      const raw = typeof value === 'string' ? value.trim() : value;
      const date = new Date(
        typeof raw === 'string' && DATE_ONLY.test(raw) ? `${raw}T${timeOfDay}-03:00` : raw,
      );
      return Number.isNaN(date.getTime()) ? Number.NaN : date.toISOString();
    })
    .refine((value) => value === null || typeof value === 'string', {
      error: 'Data de validade inválida.',
    });
}
const optionalDate = brtDate('23:59:59.999');
const optionalStartDate = brtDate('00:00:00.000');

/**
 * Número opcional não-negativo: vazio ou não-numérico vira `null`; negativo é
 * ERRO. O nome já prometia isso, mas o transform devolvia o negativo intacto e
 * o handler gravava `max_uses: 0`/`min_order_amount: -5` sem reclamar.
 */
const optionalNonNegative = z
  .union([z.string(), z.number(), z.null()])
  .transform((value) => {
    if (value === null || String(value).trim() === '') return null;
    const num = Number(value);
    return Number.isFinite(num) ? num : null;
  })
  .refine((value) => value === null || value >= 0, { error: 'Valor não pode ser negativo.' });

const couponCreateSchema = z
  .object({
    code: couponCode,
    discountType: discountType.optional(),
    discountValue: z.coerce.number({ error: 'Valor do desconto deve ser maior que zero.' }),
    validFrom: optionalStartDate.optional(),
    validUntil: optionalDate.optional(),
    maxUses: optionalNonNegative.optional(),
    maxUsesPerCustomer: optionalNonNegative.optional(),
    minOrderAmount: optionalNonNegative.optional(),
    audience: z
      .enum([
        'all',
        'customers',
        'new_customers',
        'returning_customers',
        'emails',
        'purchase_milestone',
      ])
      .optional(),
    purchasesRequired: optionalNonNegative.optional(),
    eligibleEmails: z
      .array(z.string().trim().toLowerCase().email({ error: 'E-mail de cliente inválido.' }))
      .max(500, { error: 'Limite de 500 e-mails por cupom.' })
      .optional(),
    active: z.boolean().optional(),
  })
  .refine((data) => Number.isFinite(data.discountValue) && data.discountValue > 0, {
    error: 'Valor do desconto deve ser maior que zero.',
    path: ['discountValue'],
  })
  .refine((data) => !((data.discountType || 'percent') === 'percent' && data.discountValue > 100), {
    error: 'Desconto percentual não pode passar de 100%.',
    path: ['discountValue'],
  })
  .refine((data) => data.audience !== 'emails' || (data.eligibleEmails?.length || 0) > 0, {
    error: 'Informe ao menos um e-mail elegível.',
    path: ['eligibleEmails'],
  })
  // Zero não é "sem limite": é um cupom que ninguém consegue usar. Vazio é a
  // forma de dizer "sem limite" — a mesma regra do limite por cliente abaixo.
  .refine((data) => data.maxUses == null || data.maxUses >= 1, {
    error: 'O limite de usos precisa ser 1 ou mais (vazio = sem limite).',
    path: ['maxUses'],
  })
  .refine((data) => data.maxUsesPerCustomer == null || data.maxUsesPerCustomer >= 1, {
    error: 'O limite por cliente precisa ser 1 ou mais (vazio = sem limite).',
    path: ['maxUsesPerCustomer'],
  })
  .refine((data) => data.audience !== 'purchase_milestone' || Number(data.purchasesRequired) >= 1, {
    error: 'Informe quantas compras liberam a recompensa.',
    path: ['purchasesRequired'],
  });

// ── Produtos ─────────────────────────────────────────────────────────

const productCreateSchema = z.object({
  name: z
    .unknown()
    .transform(cleanText)
    .refine((value) => value.length > 0, { error: 'name e price válidos são obrigatórios' }),
  price: money.refine((value) => value > 0, { error: 'name e price válidos são obrigatórios' }),
});

/**
 * PATCH de produto: só `active` e `featured`, e ao menos um dos dois.
 *
 * O handler já rejeitava payload vazio; a diferença é que a regra agora está
 * DECLARADA em vez de derivada de `Object.keys(payload).length === 1`, que é
 * o tipo de condição que ninguém consegue ler sem executar mentalmente.
 */
const productPatchSchema = z
  .object({
    id: uuidId,
    active: z.boolean().optional(),
    featured: z.boolean().optional(),
  })
  .refine((data) => data.active !== undefined || data.featured !== undefined, {
    error: 'Nenhum campo suportado para atualização parcial.',
  });

// ── Pedidos ──────────────────────────────────────────────────────────

// ── Devoluções ───────────────────────────────────────────────────────

// Os mesmos valores do CHECK de `refund_requests.status`
// (migration 20261031000000). O índice único `refund_requests_one_open_per_order`
// só deixa UMA solicitação fora de declined/resolved por pedido — é ele que
// vira 409 no handler quando a dona da loja reabre uma com outra ativa.
const REFUND_REQUEST_STATUSES = Object.freeze([
  'open',
  'contacted',
  'accepted',
  'declined',
  'resolved',
]);

/**
 * PUT do painel de devoluções. O `id` é uuid (PK de refund_requests) e, como
 * nos demais recursos, validar a FORMA antes de interpolar em `id=eq.<valor>`
 * é o motivo de o primitivo existir. A resposta é texto livre da dona da loja
 * (pode ter quebras de linha, por isso não passa por `cleanText`), com o teto
 * que o handler já aplicava.
 */
const refundRequestUpdateSchema = z.object({
  id: uuidId,
  status: z.enum(REFUND_REQUEST_STATUSES, { error: 'Status inválido.' }),
  response: z
    .string({ error: 'A resposta precisa ser texto.' })
    .trim()
    .max(4000, { error: 'A resposta pode ter até 4000 caracteres.' })
    .nullish()
    .transform((value) => value ?? ''),
});

// ── Publicação social ────────────────────────────────────────────────

const SOCIAL_PLATFORMS = Object.freeze([
  'facebook',
  'instagram',
  'pinterest',
  'tiktok',
  'whatsapp',
]);

/** Link opcional: vazio passa; preenchido tem de ser HTTPS (nunca http/data/js). */
const optionalHttpsUrl = z
  .string({ error: 'Use apenas links HTTPS.' })
  .trim()
  .max(2048, { error: 'Link muito longo.' })
  .refine((value) => value === '' || value.startsWith('https://'), {
    error: 'Use apenas links HTTPS.',
  })
  .optional()
  .default('');

/**
 * POST /admin/social-publish. O painel manda o formulário inteiro para toda
 * rede (`...form`), então os campos específicos de uma plataforma chegam
 * vazios para as outras — por isso são opcionais aqui e cobrados por
 * plataforma nos `refine` do fim.
 *
 * O número do WhatsApp aceita formatação ("+55 (11) 9…") e sai só com os
 * dígitos: é o que a Cloud API espera em `to`.
 */
const socialPublishSchema = z
  .object({
    platform: z
      .string({ error: 'Escolha a rede social.' })
      .trim()
      .toLowerCase()
      .pipe(z.enum(SOCIAL_PLATFORMS, { error: 'Rede social inválida.' })),
    caption: z
      .string({ error: 'A legenda precisa ser texto.' })
      .trim()
      .max(2200, { error: 'A legenda pode ter até 2200 caracteres.' })
      .optional()
      .default(''),
    mediaUrl: optionalHttpsUrl,
    link: optionalHttpsUrl,
    recipient: z
      .string({ error: 'Informe o número com DDI.' })
      .transform((value) => value.replaceAll(/\D/g, ''))
      .optional()
      .default(''),
    videoSize: z
      .union([z.number(), z.string()])
      .transform(Number)
      .refine((value) => Number.isSafeInteger(value) && value > 0, {
        error: 'Selecione um vídeo válido.',
      })
      .optional(),
    privacy: z
      .string({ error: 'Privacidade inválida.' })
      .trim()
      .max(40, { error: 'Privacidade inválida.' })
      .optional()
      .default(''),
    title: z
      .string({ error: 'O título precisa ser texto.' })
      .trim()
      .max(100, { error: 'O título pode ter até 100 caracteres.' })
      .optional()
      .default(''),
  })
  .refine(
    (data) =>
      data.platform !== 'whatsapp' || (/^\d{8,15}$/.test(data.recipient) && data.caption !== ''),
    { error: 'Informe o número com DDI e a mensagem.', path: ['recipient'] },
  )
  .refine((data) => data.platform !== 'tiktok' || data.videoSize !== undefined, {
    error: 'Selecione um vídeo válido.',
    path: ['videoSize'],
  });

// ── Usuários ─────────────────────────────────────────────────────────

// Roles que este endpoint pode ATRIBUIR. 'admin'/'master' são deliberadamente
// omitidos: promover a admin por aqui seria escalada de privilégio, já que a
// autorização do painel é decidida por `profiles.role`.
const ASSIGNABLE_ROLES = Object.freeze(['customer', 'cliente', 'seller', 'vendedor']);

const userUpdateSchema = z
  .object({
    id: uuidId,
    name: z.string().trim().optional(),
    role: z
      .string()
      .trim()
      .toLowerCase()
      .refine((value) => ASSIGNABLE_ROLES.includes(value), {
        // A mensagem antiga falava em "admin/master" até quando o pedido era
        // "support" (ADM-42) — e a tela oferecia papéis que este endpoint nunca
        // aceitou. Agora ela diz o que É aceito.
        error: 'Papel inválido. Por aqui só é possível atribuir Cliente ou Vendedor.',
      })
      .optional(),
    provider: z.string().trim().toLowerCase().optional(),
  })
  .refine(
    (data) => data.name !== undefined || data.role !== undefined || data.provider !== undefined,
    { error: 'Nenhum campo válido para atualização.' },
  );

module.exports = {
  ASSIGNABLE_ROLES,
  bigintId,
  categoryCreateSchema,
  categoryUpdateSchema,
  couponCreateSchema,
  money,
  normalizeSlug,
  productCreateSchema,
  productPatchSchema,
  refundRequestUpdateSchema,
  slug,
  socialPublishSchema,
  userUpdateSchema,
  uuidId,
};
